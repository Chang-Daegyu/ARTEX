"use client"

/**
 * 한국어 해설 — src/components/ui/field.tsx
 * 폼 필드의 묶음·레이블·설명·구분선·오류 표시.
 * 수직/수평/반응형 배치를 지원한다. FieldError는 같은 message를 합쳐 한 오류 또는 목록으로 출력하지만 검증 규칙 자체는 실행하지 않는다.
 * 컴포넌트의 data-slot은 스타일/조합의 연결점이고, className 및 나머지 props는 원래 요소로 전달된다.
 */

import { useMemo } from "react"
import { cva, type VariantProps } from "class-variance-authority"

import { cn } from "@/lib/utils"
import { Label } from "@/components/ui/label"
import { Separator } from "@/components/ui/separator"

